export type TKey = keyof Dict;
const DICTS: Record<Lang, Dict> = { ar, en, fr };

export function translator(lang: Lang) {
  const d = DICTS[lang] ?? ar;
  return (key: TKey, ...args: (string | number)[]) =>
    args.reduce<string>((s, a, i) => s.split(`{${i}}`).join(String(a)), d[key] ?? ar[key] ?? key);
}

const STORAGE_KEY = "cashback_admin_lang";

export function loadLang(): Lang {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    return LANGS.includes(v as Lang) ? (v as Lang) : "ar";
  } catch {
    return "ar";
  }
}

export function saveLang(l: Lang) {
  try {
    localStorage.setItem(STORAGE_KEY, l);
  } catch {
    /* بدون تخزين: اللغة للجلسة فقط */
  }
}
